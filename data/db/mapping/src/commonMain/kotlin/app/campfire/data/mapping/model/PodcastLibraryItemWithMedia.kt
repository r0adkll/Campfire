  ctimeMs = ctimeMs,
  birthtimeMs = birthtimeMs,
  addedAt = addedAt,
  updatedAt = updatedAt,
  isMissing = isMissing,
  isInvalid = isInvalid,
  mediaType = mediaType,
  numFiles = numFiles,
  size = size,
  serverUrl = serverUrl,
  mediaId = mediaId,
  podcastLibraryItemId = podcastLibraryItemId,
  coverPath = coverPath,
  tags = tags,
  sizeInBytes = sizeInBytes,
  numEpisodes = numEpisodes,
