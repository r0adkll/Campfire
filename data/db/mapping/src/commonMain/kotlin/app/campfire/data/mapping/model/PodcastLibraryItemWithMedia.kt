/**
 * Common representation of a podcast library item joined with its [podcastMedia] row.
 * Mirrors [LibraryItemWithMedia] for the book path. The [LibraryItemDao.hydratePodcastItem]
 * function reads `podcastEpisode` rows separately and composes the full domain LibraryItem.
 */
data class PodcastLibraryItemWithMedia(
  val id: String,
  val ino: String,
  val libraryId: String,
  val oldLibraryItemId: String?,
  val folderId: String,
  val path: String,
  val relPath: String,
  val isFile: Boolean,
  val mtimeMs: Long,
  val ctimeMs: Long,
  val birthtimeMs: Long,
  val addedAt: Long,
  val updatedAt: Long,
  val isMissing: Boolean,
  val isInvalid: Boolean,
  val mediaType: MediaType,
  val numFiles: Int,
  val size: Long,
  val serverUrl: String,

  val mediaId: String,
  // libraryItemId is also a column on podcastMedia (FK back), echo'd here for parity
  // with the DB row shape produced by SELECT libraryItem.*, podcastMedia.*.
  val podcastLibraryItemId: String,
  val coverPath: String?,
  val tags: List<String>?,
  val sizeInBytes: Long,
  val numEpisodes: Int,
  val autoDownloadEpisodes: Boolean,
  val autoDownloadSchedule: String?,
  val lastEpisodeCheckMillis: Long?,
  val maxEpisodesToKeep: Int,
  val maxNewEpisodesToDownload: Int,
  val latestEpisodePublishedAtMillis: Long?,

  val metadata_title: String?,
  val metadata_titleIgnorePrefix: String?,
  val metadata_author: String?,
  val metadata_description: String?,
  val metadata_releaseDate: String?,
  val metadata_genres: List<String>?,
  val metadata_feedUrl: String?,
  val metadata_imageUrl: String?,
  val metadata_itunesPageUrl: String?,
  val metadata_itunesId: String?,
  val metadata_itunesArtistId: String?,
  val metadata_explicit: Boolean,
  val metadata_language: String?,
  val metadata_podcastType: String?,

  val userMediaProgress: LibraryItemProgress? = null,
)

